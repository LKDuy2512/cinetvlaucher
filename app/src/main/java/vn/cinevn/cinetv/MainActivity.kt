create table if not exists public.cinevn_comments (
  id bigint generated by default as identity primary key,
  movie_slug text not null,
  movie_title text not null default '',
  user_id uuid not null references auth.users(id) on delete cascade,
  user_name text not null default 'Thành viên CineVN',
  avatar_url text not null default '',
  body text not null check (char_length(body) between 1 and 1200),
  created_at timestamptz not null default now()
);
create index if not exists cinevn_comments_movie_created_idx
  on public.cinevn_comments (movie_slug, created_at desc);
alter table public.cinevn_comments enable row level security;
drop policy if exists "Anyone can read CineVN comments" on public.cinevn_comments;
create policy "Anyone can read CineVN comments" on public.cinevn_comments
  for select to anon, authenticated using (true);
drop policy if exists "Signed-in users can post CineVN comments" on public.cinevn_comments;
create policy "Signed-in users can post CineVN comments" on public.cinevn_comments
  for insert to authenticated with check (auth.uid() = user_id);
